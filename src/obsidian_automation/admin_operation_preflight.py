"""Non-authoritative preflight for an eventual #300 local operation broker.

This module NEVER executes systemctl, changes files, or authorizes a live effect.
Broker-side, live reobservation, deployment exclusion, audit and durable
idempotency must be established independently before operations can be enabled.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
import re
from typing import Mapping

from .admin_status import SERVICES

ACTIONS = frozenset(("pause", "resume", "run_once"))
_SERVICE_IDS = frozenset(spec.identifier for spec in SERVICES)
_REQUEST_ID = re.compile(
    r"[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}"
)
_TIME_PATTERN = re.compile(r"\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d(?:\.\d{1,6})?(?:Z|\+00:00)")
MAX_OBSERVATION_AGE = timedelta(seconds=30)
_REQUIRED = frozenset(("version", "request_id", "service_id", "action", "observed_at"))


class PreflightRejected(ValueError):
    """Fixed-code rejection; never echo arbitrary browser or systemd input."""

    def __init__(self, reason: str):
        super().__init__(reason)
        self.reason = reason


@dataclass(frozen=True)
class OperationCandidate:
    """A validated candidate, NOT execution authorization or durable approval."""

    request_id: str
    service_id: str
    action: str
    observed_at: str
    authority: str = "requires_broker_live_recheck"

    def as_public_dict(self) -> dict[str, str]:
        return {
            "request_id": self.request_id,
            "service_id": self.service_id,
            "action": self.action,
            "observed_at": self.observed_at,
            "authority": self.authority,
        }


def _parse_time(value: object) -> datetime:
    if not isinstance(value, str) or not _TIME_PATTERN.fullmatch(value):
        raise PreflightRejected("invalid_observation_time")
    try:
        observed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError as exc:
        raise PreflightRejected("invalid_observation_time") from exc
    if observed.tzinfo is None or observed.utcoffset() != timedelta(0):
        raise PreflightRejected("invalid_observation_time")
    return observed.astimezone(timezone.utc)


def preflight_operation(
    request: Mapping[str, object],
    observation: Mapping[str, object],
    *,
    now: datetime,
    deployment_quiescent: bool = False,
) -> OperationCandidate:
    """Preflight against a locally acquired observation (never browser-provided).

    The default fails closed until the privileged local broker proves that
    deployment and update intents are quiescent. Even a returned candidate
    cannot be executed without new live evidence and durable broker checks.
    """
    if not isinstance(request, dict) or frozenset(request) != _REQUIRED:
        raise PreflightRejected("invalid_request")
    version = request["version"]
    if type(version) is not int or version != 1:
        raise PreflightRejected("invalid_version")
    rid = request["request_id"]
    if not isinstance(rid, str) or not _REQUEST_ID.fullmatch(rid):
        raise PreflightRejected("invalid_request_id")
    sid = request["service_id"]
    if not isinstance(sid, str) or sid not in _SERVICE_IDS:
        raise PreflightRejected("unknown_service")
    action = request["action"]
    if not isinstance(action, str) or action not in ACTIONS:
        raise PreflightRejected("unknown_action")
    if deployment_quiescent is not True:
        raise PreflightRejected("deployment_authority_unverified")
    if not isinstance(now, datetime) or now.tzinfo is None:
        raise PreflightRejected("invalid_clock")
    if not isinstance(observation, dict):
        raise PreflightRejected("invalid_observation")
    recorded = observation.get("generated_at")
    observed_time = _parse_time(recorded)
    if request["observed_at"] != recorded:
        raise PreflightRejected("stale_observation")
    age = now.astimezone(timezone.utc) - observed_time
    if age < timedelta(0) or age > MAX_OBSERVATION_AGE:
        raise PreflightRejected("stale_observation")
    services = observation.get("services")
    if not isinstance(services, list):
        raise PreflightRejected("invalid_observation")
    matches = [s for s in services if isinstance(s, dict) and s.get("id") == sid]
    if len(matches) != 1:
        raise PreflightRejected("unverifiable_service")
    state = matches[0]
    schedule = state.get("schedule")
    execution = state.get("latest_execution")
    health = state.get("health")
    # Use exact combinations generated by admin_status.aggregate_status;
    # independently familiar enum values are not enough to establish safety.
    if schedule not in ("scheduled", "paused") or execution not in (
        "succeeded", "failed", "not_observed",
    ):
        raise PreflightRejected("unverifiable_service")
    expected_health = (
        "failed" if execution == "failed"
        else "paused" if schedule == "paused"
        else "observed_success" if execution == "succeeded"
        else "unverified"
    )
    if health != expected_health:
        raise PreflightRejected("inconsistent_service_state")
    if action == "pause" and schedule != "scheduled":
        raise PreflightRejected("operation_state_mismatch")
    if action == "resume" and schedule != "paused":
        raise PreflightRejected("operation_state_mismatch")
    if action == "run_once" and schedule != "scheduled":
        raise PreflightRejected("operation_state_mismatch")
    return OperationCandidate(rid, sid, action, recorded)
