"""#472 R2/B1 opt-in effect-time recurring Writer adapter (NOT deployed).

The normal application still wires FormatterJob(writer=None). Construction of
this adapter alone is NOT an approval. A separately operated, durable run
authority, approved policy verifier and provider capability verifier must all
be injected. No WebUI, Scheduler or CLI creates this adapter.

All effects are delegated to the existing CAS Writer with its immutable
operation marker; no PUT payload is generated by this module.
"""
from __future__ import annotations

import threading
from dataclasses import replace
from pathlib import Path
from typing import Callable

from .core_promotion_transport import HTTPTransport, _real_http_request
from .vault_format_canary_binding import _generation, _vault_root
from .vault_format_recurring_admission import (
    RecurringAdmission, RecurringPolicy, _bounded_metadata,
    _policy_digest, prepare_recurring_admission,
)
from .vault_format_writer import FormatWriteError, _binding, apply_plan, _validated_plan

# Each verifier is supplied by a separately trusted authority, not by a
# caller-controlled API parameter. Return True *only* on an exact durable proof.
PolicyVerifier = Callable[[str, str, str, str], bool]
RunVerifier = Callable[[str, str, str, str], bool]
ProviderVerifier = Callable[[str, str, str], bool]


class RecurringEffectWriter:
    """Explicit opt-in CAS binding for one admitted run, never normal runtime.

    The run ID is fixed at construction. A new instance is needed for a new
    scheduled run. The run verifier must confirm durable, authorized run state
    and ensure no stale generation/Plan is admitted; this class alone cannot
    establish that verifier's source of truth. Cross-process credential rotation
    must be quiesced by a separately approved deployment.
    """

    def __init__(
        self, shared, source_generation: Callable[[], str | None],
        policy: RecurringPolicy, run_id: str, receipt_root: Path, *,
        policy_verifier: PolicyVerifier | None = None,
        run_verifier: RunVerifier | None = None,
        provider_verifier: ProviderVerifier | None = None,
        transport: HTTPTransport | None = None,
    ) -> None:
        if type(policy) is not RecurringPolicy:
            raise FormatWriteError("recurring_policy_invalid")
        # Pin all scalars before any user callback; no mutable policy instance
        # from the caller is retained.
        pinned = replace(policy)
        _policy_digest(pinned)
        if (type(run_id) is not str or len(run_id) != 32
                or any(c not in "0123456789abcdef" for c in run_id)):
            raise FormatWriteError("recurring_run_invalid")
        if not isinstance(receipt_root, Path) or not receipt_root.is_absolute():
            raise FormatWriteError("recurring_receipt_root_invalid")
        mutex = getattr(shared, "_lock", None)
        if (not callable(getattr(shared, "load_nextcloud", None))
                or not callable(getattr(mutex, "__enter__", None))
                or not callable(getattr(mutex, "__exit__", None))
                or not callable(source_generation)):
            raise FormatWriteError("recurring_source_unavailable")
        self._shared = shared
        self._source_generation = source_generation
        self._policy = pinned
        self._run_id = run_id
        self._receipt_root = receipt_root
        self._policy_verifier = policy_verifier
        self._run_verifier = run_verifier
        self._provider_verifier = provider_verifier
        self._transport = transport
        self._gate = threading.Lock()

    def __call__(self, plan: dict) -> dict:
        if (not callable(self._policy_verifier)
                or not callable(self._run_verifier)
                or not callable(self._provider_verifier)):
            raise FormatWriteError("recurring_effect_authority_missing")

        # Do not block a second caller behind a long WebDAV effect and then
        # accidentally treat the queued caller as a fresh authorized run.
        # The guarded CAS Writer's durable operation ID remains the replay fence.
        if not self._gate.acquire(blocking=False):
            raise FormatWriteError("recurring_effect_busy")
        try:
            return self._execute_once(plan)
        finally:
            self._gate.release()

    def _execute_once(self, plan: dict) -> dict:
        # Copy only bounded Plan metadata; the caller may mutate the Plan
        # while any injected verifier runs. The CAS Writer uses this
        # independent snapshot for its final validation and effect.
        frozen = _bounded_metadata(plan)
        plan_sha, _ = _validated_plan(frozen)
        # All externally managed verifiers execute OUTSIDE SetupStore._lock:
        # they may need a different worker to read the store in order to
        # complete. A failed verifier never starts a remote request.
        proposal = prepare_recurring_admission(
            frozen, self._policy, self._run_id,
            current_generation=self._source_generation,
            verify_operator_policy=self._policy_verifier,
        )
        if proposal is None:
            raise FormatWriteError("recurring_no_effect")
        if proposal.plan_sha256 != plan_sha:
            raise FormatWriteError("recurring_plan_changed")

        def require_policy() -> None:
            # A policy can be revoked after the initial Plan admission.
            # Always validate its PINNED digest and identity, never the
            # caller-owned policy object.
            try:
                result = self._policy_verifier(
                    proposal.policy_sha256, proposal.source_generation,
                    proposal.account_binding_sha256,
                    proposal.provider_proof_sha256,
                )
            except Exception:
                raise FormatWriteError("recurring_policy_unverified") from None
            if result is not True:
                raise FormatWriteError("recurring_policy_unverified")

        def require_run() -> None:
            try:
                result = self._run_verifier(
                    proposal.run_id, proposal.plan_sha256,
                    proposal.policy_sha256, proposal.operation_id,
                )
            except Exception:
                raise FormatWriteError("recurring_run_unverified") from None
            if result is not True:
                raise FormatWriteError("recurring_run_unverified")

        def require_provider() -> None:
            try:
                result = self._provider_verifier(
                    proposal.provider_proof_sha256,
                    proposal.source_generation,
                    proposal.account_binding_sha256,
                )
            except Exception:
                raise FormatWriteError("recurring_provider_unverified") from None
            if result is not True:
                raise FormatWriteError("recurring_provider_unverified")

        require_policy()
        require_run()
        require_provider()
        # Obtain only the current canonical credential snapshot under the
        # in-process store lock. No external verifier runs inside that lock.
        with self._shared._lock:
            try:
                details = self._shared.load_nextcloud()
            except Exception:
                raise FormatWriteError("recurring_connection_missing") from None
            if type(details) is not dict:
                raise FormatWriteError("recurring_connection_missing")
            try:
                base = _vault_root(details)
                generation = _generation(details)
                binding = _binding(base, details["nextcloud_user"])
            except Exception:
                raise FormatWriteError("recurring_connection_invalid") from None
            if generation != proposal.source_generation:
                raise FormatWriteError("recurring_source_generation_changed")
            if binding != proposal.account_binding_sha256:
                raise FormatWriteError("recurring_account_binding_changed")

        def observe_generation() -> str:
            # An injected source callback may wait for a different worker
            # that reads SetupStore. Never run it under SetupStore._lock.
            try:
                observed = self._source_generation()
            except Exception:
                raise FormatWriteError("recurring_source_unavailable") from None
            if type(observed) is not str or observed != generation:
                raise FormatWriteError("recurring_source_generation_changed")
            return observed

        def check_connection_locked(observed: str) -> None:
            # Called under SetupStore._lock, after all external callbacks.
            # Even if generation changed between observation and lock
            # acquisition, the credential hash/binding below rejects it.
            if type(observed) is not str or observed != generation:
                raise FormatWriteError("recurring_source_generation_changed")
            try:
                latest = self._shared.load_nextcloud()
            except Exception:
                raise FormatWriteError("recurring_connection_unavailable") from None
            if type(latest) is not dict:
                raise FormatWriteError("recurring_connection_missing")
            try:
                current_base = _vault_root(latest)
                current_generation = _generation(latest)
                current_binding = _binding(current_base, latest["nextcloud_user"])
            except Exception:
                raise FormatWriteError("recurring_connection_invalid") from None
            if current_generation != generation:
                raise FormatWriteError("recurring_source_generation_changed")
            if current_binding != binding:
                raise FormatWriteError("recurring_account_binding_changed")

        # The actual provider callback may carry real credentials; only
        # explicitly supplied transport functions are used. A falsy callable
        # must NOT silently select real HTTP.
        delegate = _real_http_request if self._transport is None else self._transport
        if not callable(delegate):
            raise FormatWriteError("recurring_transport_invalid")

        def guarded_transport(**kwargs):
            # The approval callbacks run without the credential lock, and
            # are required to be read-only/idempotent. Revocation observed
            # at this pre-request boundary stops further requests.
            #
            # This is NOT an atomic remote revocation lease: a revocation
            # after these checks may race a request already being sent.
            require_policy()
            require_run()
            require_provider()
            observed = observe_generation()
            with self._shared._lock:
                # The canonical credential snapshot is checked under the
                # lock, but the user-supplied transport must NOT execute
                # within it. A transport may wait for a worker that reads
                # SetupStore, and could otherwise deadlock this thread.
                check_connection_locked(observed)
            # Rotation after this check may race the request. An externally
            # governed lease/stop-drain protocol is required for deployment.
            return delegate(**kwargs)

        require_policy()
        require_run()
        require_provider()
        observed = observe_generation()
        with self._shared._lock:
            check_connection_locked(observed)

        # Reuse the existing canonical CAS Writer: it reserves the operation
        # marker before HTTP; a replay with the same run_id is rejected even
        # when a changed Plan is presented. This is root-local, not a global
        # replay service. No HTTP occurs without all injected authorities.
        return apply_plan(
            frozen, selected_paths=proposal.selected_paths,
            enabled=True, cas_server_verified=True,
            receipt_dir=self._receipt_root,
            base_url=base,
            username=details["nextcloud_user"],
            password=details["nextcloud_password"],
            operation_id=proposal.operation_id,
            transport=guarded_transport,
        )
